from queue import PriorityQueue
def a_star_search(graph,start,goal,h):
    open_set = PriorityQueue()
    open_set.put((0,start))

    g_score={node : float ('inf') for node in graph}
    g_score[start]=0

    came_from={}

    while not open_set.empty():
        current_f,current=open_set.get()
        if current == goal:
            path=[]
            while current in came_from:
                path.append(current)
                current=came_from[current]
            path.append(start)
            path.reverse()
            return path,g_score[goal]


        for neighbour, cost in graph[current]:
            new_cost= g_score[current]+cost

            if new_cost<g_score[neighbour]:
                g_score[neighbour]=new_cost
                priority = new_cost +h(neighbour)

                open_set.put((priority,neighbour))
                came_from[neighbour]=current
    return None,float('inf')

graph={
    'A':[('B',1),('C',4)],
    'B':[('A',1),('C',2),('D',5)],
    'C':[('A',4),('B',2),('D',1)],
    'D':[('B',5),('C',1)]
}

heuristic={

           'A':7,
           'B':6,
           'C':2,
           'D':0
}

def h(node):
  return heuristic[node]

path ,cost=a_star_search(graph,'A','D',h)

